import assert from "node:assert/strict";
import { mkdir, readFile, symlink, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { expect, test } from "vitest";
import { withFixture } from "./fixture.js";

async function writeProject(root: string, files: Record<string, string>) {
  for (const [path, content] of Object.entries(files)) {
    const file = join(root, path);
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, content);
  }
}

const jsConfig = JSON.stringify({
  compilerOptions: { allowJs: true, noEmit: true, module: "NodeNext", types: [] },
  include: ["**/*"],
});

const buildConfig = JSON.stringify({
  compilerOptions: { allowJs: true, module: "NodeNext", rootDir: ".", outDir: "dist", types: [] },
  include: ["temporal/**/*"],
});

test("inspect keeps nested discovery and package ownership without executing the application", async () => {
  await withFixture([], async (fixture) => {
    const application = "application with spaces";
    const project = join(fixture.project, application);
    const markers = join(fixture.root, "execution-markers");
    await mkdir(markers);
    const primary = "temporal/workflows/primary.mjs";
    const secondary = "another/temporal/activities/notifications/send.mjs";
    const nested = "nested";
    const nestedSource = `${nested}/temporal/workflows/child.mjs`;
    const authored = "temporal/activities/authored.mjs";
    const candidates: [string, string] = [
      "temporal/workers/notification/first.mjs",
      "temporal/workers/notification/second.mjs",
    ];
    const declared = `${nested}/temporal/workers/child/start.mjs`;
    const unavailable = "temporal/workers/unavailable/main.mts";
    const ignoredSources = {
      "temporal/workflows/lib/helper.mjs": "export function ignoredHelper() {}\n",
      "temporal/workflows/ignored.test.mjs": "export function ignoredTest() {}\n",
      "temporal/workflows/ignored.generated.mjs":
        "// Code generated by Genesys. Do not edit.\nexport function ignoredGenerated() {}\n",
      ".gsys/temporal/workflows/previous.mjs": "export function ignoredPrevious() {}\n",
    };
    await writeProject(project, {
      "package.json": JSON.stringify({
        dependencies: { "@temporalio/worker": "1.25.0" },
        scripts: { build: "node build.mjs" },
      }),
      "tsconfig.json": jsConfig,
      [`${nested}/package.json`]: JSON.stringify({ main: "temporal/workers/child/start.mjs" }),
      [`${nested}/tsconfig.json`]: jsConfig,
      [primary]: 'export async function primary() { return "primary"; }\n',
      [secondary]: 'export async function send() { return "secondary"; }\n',
      [nestedSource]: 'export async function child() { return "child"; }\n',
      "lib/mark.mjs": `import { writeFileSync } from "node:fs";
import { join } from "node:path";
export function mark(name) { writeFileSync(join(process.env.GSYS_TEST_MARKERS, name), name); }
`,
      [authored]: `import { mark } from "../../lib/mark.mjs";
mark("import");
class Greeter {
  constructor() { mark("constructor"); }
  greet() { return "hello"; }
}
export const instance = new Greeter();
function makeActivities() {
  mark("factory");
  return { greeting: () => instance.greet() };
}
export const activities = makeActivities();
`,
      "build.mjs": 'import { mark } from "./lib/mark.mjs"; mark("build");\n',
      [candidates[0]]: `import { Worker } from "@temporalio/worker";
import { activities } from "../../activities/authored.mjs";
function nativeOptions() { return { taskQueue: "notifications", activities }; }
await Worker.create(nativeOptions());
`,
      [candidates[1]]: 'console.log("second");\n',
      [declared]: 'export const startup = "declared";\n',
      [unavailable]: 'console.log("requires native emit");\n',
      ...ignoredSources,
    });

    const env = { GSYS_TEST_MARKERS: markers };
    const inspection = await fixture.gsys(["inspect", application], { env });
    expect(inspection).toMatchObject({ code: 0, signal: null });
    const manifest: unknown = JSON.parse(inspection.stdout);
    expect(manifest).toMatchObject({
      packages: [
        { id: "typescript:.", root: ".", manifests: ["package.json"] },
        { id: "typescript:nested", root: nested, manifests: ["nested/package.json"] },
      ],
      entries: expect.arrayContaining([
        {
          id: primary,
          path: primary,
          language: "typescript",
          role: "workflow",
          discoveryRoot: "temporal",
          packageId: "typescript:.",
        },
        {
          id: secondary,
          path: secondary,
          language: "typescript",
          role: "activity",
          discoveryRoot: "another/temporal",
          packageId: "typescript:.",
        },
        {
          id: nestedSource,
          path: nestedSource,
          language: "typescript",
          role: "workflow",
          discoveryRoot: "nested/temporal",
          packageId: "typescript:nested",
        },
      ]),
      definitions: expect.arrayContaining(
        [
          [primary, "primary", "workflow"],
          [secondary, "send", "activity"],
          [nestedSource, "child", "workflow"],
        ].map(([path, name, kind]) =>
          expect.objectContaining({ kind, entryId: path, identity: { state: "resolved", name } }),
        ),
      ),
      workers: expect.arrayContaining([
        expect.objectContaining({ name: "notification", packageId: "typescript:." }),
        expect.objectContaining({ name: "unavailable", source: { path: unavailable } }),
        expect.objectContaining({
          name: "child",
          packageId: "typescript:nested",
          source: { path: declared },
          start: { executable: "node", args: ["temporal/workers/child/start.mjs"], cwd: nested },
        }),
      ]),
    });
    for (const path of Object.keys(ignoredSources)) expect(inspection.stdout).not.toContain(path);
    for (const name of ["notification", "unavailable"]) {
      expect(manifest).not.toMatchObject({
        workers: expect.arrayContaining([
          expect.objectContaining({ name, start: expect.anything() }),
        ]),
      });
    }
    expect(inspection.stderr).toContain(
      `warning typescript.activity-instance-required ${authored}`,
    );
    expect(inspection.stderr).toContain(
      `warning typescript.worker-options-unresolved ${candidates[0]}`,
    );
    expect(inspection.stderr).toContain(
      `warning typescript.worker-output-unresolved ${unavailable}`,
    );
    const diagnostics: unknown = JSON.parse(
      await readFile(join(project, ".gsys/discovery/diagnostics.json"), "utf8"),
    );
    expect(diagnostics).toEqual(
      expect.arrayContaining([
        expect.objectContaining({
          code: "typescript.worker-entrypoint-ambiguous",
          severity: "warning",
          related: candidates.map((path) => ({ path })),
        }),
      ]),
    );

    for (const name of ["import", "constructor", "factory", "build"])
      await expect(readFile(join(markers, name))).rejects.toMatchObject({ code: "ENOENT" });

    const nativeAssembly = await fixture.run(
      "node",
      [
        "--input-type=module",
        "-e",
        `const { activities } = await import("./${authored}"); console.log(activities.greeting());`,
      ],
      { cwd: project, env },
    );
    expect(nativeAssembly).toMatchObject({ code: 0, stdout: "hello\n" });
    expect(
      await fixture.run("npm", ["run", "build", "--silent"], { cwd: project, env }),
    ).toMatchObject({ code: 0 });
    for (const name of ["import", "constructor", "factory", "build"])
      expect(await readFile(join(markers, name), "utf8")).toBe(name);
  });
}, 240_000);

test("installed commands keep complete inspect JSON on stdout and report invocation, source, and dependency failures", async () => {
  await withFixture([], async (fixture) => {
    for (const args of [[], ["--help"], ["dev", "-h"]]) {
      const help = await fixture.gsys(args);
      expect(help).toMatchObject({ code: 0, signal: null, stderr: "" });
      expect(help.stdout).toMatch(/^Usage: gsys <inspect\|build\|dev>/);
    }
    const version = await fixture.gsys(["--version"]);
    expect(version).toMatchObject({ code: 0, signal: null, stderr: "" });
    expect(version.stdout).toMatch(/^\d+\.\d+\.\d+(?:[-+][\w.-]+)?\n$/);
    const installedPackage: unknown = JSON.parse(
      await readFile(join(fixture.root, "consumer/node_modules/@genesys/cli/package.json"), "utf8"),
    );
    expect(installedPackage).toHaveProperty("version", version.stdout.trim());
    for (const args of [["unknown"], ["inspect", "--unknown"], ["dev", "--unknown"]]) {
      const invalid = await fixture.gsys(args);
      expect(invalid).toMatchObject({ code: 1, signal: null, stdout: "" });
      expect(invalid.stderr).toMatch(/^gsys: .*?(?:unsupported|unknown)/i);
    }

    const workflow = "temporal/workflows/large.mts";
    const definitions = Array.from(
      { length: 4_096 },
      (_, i) => `export async function workflow_${i}() { return ${i}; }`,
    );
    await writeProject(fixture.project, {
      "package.json": '{"type":"module","dependencies":{"@temporalio/worker":"1.25.0"}}',
      "tsconfig.json": jsConfig,
      [workflow]: definitions.join("\n"),
    });
    const large = await fixture.gsys(["inspect"]);
    expect(large).toMatchObject({ code: 0, signal: null });
    expect(Buffer.byteLength(large.stdout)).toBeGreaterThan(1024 * 1024);
    const recorded: unknown = JSON.parse(
      await readFile(join(fixture.project, ".gsys/discovery/manifest.json"), "utf8"),
    );
    assert(recorded && typeof recorded === "object");
    const stdout: unknown = JSON.parse(large.stdout);
    expect(stdout).toHaveProperty("definitions.length", definitions.length);
    expect(stdout).toEqual({ ...recorded, workers: [] });
    expect(large.stderr).toContain("info typescript.sdk-version package.json:");
    expect(large.stderr).toContain("installed: unresolved");

    const absentDependency = 'export { Worker as missing } from "@temporalio/worker";\n';
    await writeProject(fixture.project, { [workflow]: absentDependency });
    const missing = await fixture.gsys(["inspect"]);
    expect(missing).toMatchObject({ code: 0, signal: null });
    const missingManifest: unknown = JSON.parse(missing.stdout);
    expect(missingManifest).toMatchObject({ definitions: [], workers: [] });
    expect(missing.stderr).toContain(
      `warning typescript.TS2307 ${workflow}: Cannot find module '@temporalio/worker'`,
    );

    await writeProject(fixture.project, {
      [workflow]: `${absentDependency}export const broken = ;\n`,
    });
    const failed = await fixture.gsys(["inspect"]);
    expect(failed).toMatchObject({ code: 1, signal: null });
    const failedManifest: unknown = JSON.parse(failed.stdout);
    expect(failedManifest).toMatchObject({ definitions: [], workers: [] });
    expect(failed.stderr).toContain(
      `warning typescript.TS2307 ${workflow}: Cannot find module '@temporalio/worker'`,
    );
    expect(failed.stderr).toContain(`error typescript.TS1109 ${workflow}: Expression expected.`);

    const worker = "temporal/workers/missing/start.mjs";
    await writeProject(fixture.project, {
      "package.json": JSON.stringify({
        dependencies: { "@temporalio/worker": "1.25.0" },
        main: worker,
      }),
      "tsconfig.json": buildConfig,
      [workflow]: absentDependency,
      [worker]: 'console.log("Worker entrypoint");\n',
    });
    const failedBuild = await fixture.gsys(["build"]);
    expect(failedBuild).toMatchObject({ code: 1, signal: null });
    expect(failedBuild.stderr).toContain("Install the application's TypeScript compiler");
    await expect(
      readFile(join(fixture.project, ".gsys/compile/manifest.json")),
    ).rejects.toMatchObject({ code: "ENOENT" });
  });
}, 240_000);

test("inspect names ambiguous native projects and fails when the native analysis tool is missing", async () => {
  await withFixture([["dotnet", "--version"]], async (fixture) => {
    const projects: [string, string] = ["First.csproj", "Second.csproj"];
    const source = "temporal/workers/demo/Program.cs";
    const csproj =
      '<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><TargetFramework>net10.0</TargetFramework><OutputType>Exe</OutputType></PropertyGroup></Project>\n';
    await writeProject(fixture.project, {
      [projects[0]]: csproj,
      [projects[1]]: csproj,
      [source]: 'System.Console.WriteLine("native candidate");\n',
    });
    const ambiguous = await fixture.gsys(["inspect"]);
    expect(ambiguous).toMatchObject({ code: 1, signal: null });
    expect(ambiguous.stderr).toContain("warning package.ambiguous-context .:");
    expect(ambiguous.stderr).toContain("error dotnet.project-unresolved .:");
    expect(ambiguous.stderr).toContain("remain available through native assembly");
    expect(ambiguous.stderr).toContain("tooling limit");
    const manifest: unknown = JSON.parse(ambiguous.stdout);
    expect(manifest).toMatchObject({
      packages: [{ id: "dotnet:.", manifests: projects }],
      entries: [{ path: source, packageId: "dotnet:." }],
      workers: [],
    });
    const diagnostics: unknown = JSON.parse(
      await readFile(join(fixture.project, ".gsys/discovery/diagnostics.json"), "utf8"),
    );
    expect(diagnostics).toEqual(
      expect.arrayContaining([
        expect.objectContaining({
          code: "package.ambiguous-context",
          related: projects.map((path) => ({ path })),
        }),
      ]),
    );

    const nodeBin = join(fixture.root, "node-bin");
    await mkdir(nodeBin);
    await symlink(process.execPath, join(nodeBin, "node"));
    const unavailable = await fixture.gsys(["inspect"], { env: { PATH: nodeBin } });
    expect(unavailable).toMatchObject({ code: 1, signal: null });
    expect(unavailable.stderr).toContain("error dotnet.analysis-unavailable .:");
    expect(unavailable.stderr).toContain("requires .NET SDK 10");
    expect(unavailable.stderr).toContain("spawn dotnet ENOENT");
    const unavailableManifest: unknown = JSON.parse(unavailable.stdout);
    expect(unavailableManifest).toMatchObject({ definitions: [], workers: [] });
  });
}, 360_000);

test("build keeps native package logs off the published JSON stdout", async () => {
  await withFixture([], async (fixture) => {
    await writeProject(fixture.project, {
      "package.json": JSON.stringify({
        main: "temporal/workers/demo/start.mjs",
      }),
      "tsconfig.json": buildConfig,
      "temporal/workers/demo/start.mjs": 'console.log("Worker entrypoint");\n',
      "node_modules/typescript/bin/tsc": `const { cpSync } = require("node:fs");
cpSync("temporal", "dist/temporal", { recursive: true });
console.log("native compiler log");
`,
    });
    const build = await fixture.gsys(["build"]);
    expect(build).toMatchObject({ code: 0, signal: null });
    const selected: unknown = JSON.parse(
      await readFile(join(fixture.project, ".gsys/compile/manifest.json"), "utf8"),
    );
    assert(selected && typeof selected === "object" && "id" in selected);
    assert(typeof selected.id === "string");
    expect(build.stdout.slice(0, 160)).not.toContain("native compiler log");
    const printed: unknown = JSON.parse(build.stdout);
    expect(printed).toMatchObject({ schemaVersion: 1, id: selected.id });
    expect(build.stderr).toContain("native compiler log");
  });
}, 240_000);
