using System.Text;
using System.Text.Json;
using Microsoft.CodeAnalysis;
using static Genesys.Analysis.NativeSymbols;

namespace Genesys.Analysis;

internal sealed class RegistrationEmitter(string suffix, IReadOnlyList<Registration> registrations)
{
    private readonly StringBuilder code = new();

    public static IReadOnlyList<GeneratedArtifact> Emit(
        AnalysisInput input, ProjectContext project, RegistrationPlan plan)
    {
        if (plan.Registrations.Count == 0)
            return [];
        var emitter = new RegistrationEmitter(input.Suffix, plan.Registrations);
        var path = input.Package.Root == "."
            ? "GenesysRegistration.g.cs"
            : input.Package.Root + "/GenesysRegistration.g.cs";
        return [new(path, emitter.Render(project.HasHosting), "registration")];
    }

    private string Render(bool hasHosting)
    {
        code.Append("// Generated by Genesys. Native SDK validation and application construction remain authoritative.\n#nullable enable\nnamespace Genesys.Generated\n{\n    public static class Registration_")
            .Append(suffix).Append("\n    {\n");
        if (hasHosting)
            AppendHosting();
        AppendWorkflows();
        var staticTypes = registrations.Where(item => item.Kind == "activity" && HasOnlyStaticActivities(item.Type)).ToArray();
        AppendStaticActivities(staticTypes);
        AppendInstances("activity", "AddGenesysActivities", staticTypes);
        AppendInstances("nexus", "AddGenesysNexus", staticTypes);
        code.Append("    }\n}\n");
        return code.ToString();
    }

    private string TypeExpression(INamedTypeSymbol type) =>
        "typeof(Registration_" + suffix + ").Assembly.GetType("
        + JsonSerializer.Serialize(MetadataName(type)) + ", throwOnError: true)!";

    private void AppendHosting()
    {
        code.Append("        public static global::Temporalio.Extensions.Hosting.ITemporalWorkerServiceOptionsBuilder AddGenesys(this global::Temporalio.Extensions.Hosting.ITemporalWorkerServiceOptionsBuilder builder)\n        {\n");
        foreach (var (kind, type) in registrations)
        {
            var method = kind switch
            {
                "workflow" => "AddWorkflow",
                "activity" => "ApplyTemporalActivities",
                _ => "ApplyNexusService",
            };
            code.Append("            global::Temporalio.Extensions.Hosting.TemporalWorkerServiceOptionsBuilderExtensions.")
                .Append(method).Append("(builder, ").Append(TypeExpression(type)).Append(");\n");
        }
        code.Append("            return builder;\n        }\n");
    }

    private void AppendWorkflows()
    {
        code.Append("        public static global::Temporalio.Worker.TemporalWorkerOptions AddGenesysWorkflows(this global::Temporalio.Worker.TemporalWorkerOptions options)\n        {\n");
        foreach (var (_, type) in registrations.Where(item => item.Kind == "workflow"))
            code.Append("            options.AddWorkflow(").Append(TypeExpression(type)).Append(");\n");
        code.Append("            return options;\n        }\n");
    }

    private void AppendStaticActivities(IReadOnlyList<Registration> staticTypes)
    {
        code.Append("        public static global::Temporalio.Worker.TemporalWorkerOptions AddGenesysStaticActivities(this global::Temporalio.Worker.TemporalWorkerOptions options)\n        {\n");
        foreach (var (_, type) in staticTypes)
            code.Append("            options.AddAllActivities(").Append(TypeExpression(type)).Append(", null);\n");
        code.Append("            return options;\n        }\n");
    }

    private void AppendInstances(string kind, string methodName, IReadOnlyList<Registration> staticTypes)
    {
        code.Append("        public static global::Temporalio.Worker.TemporalWorkerOptions ").Append(methodName)
            .Append("(this global::Temporalio.Worker.TemporalWorkerOptions options, object instance)\n        {\n");
        var instanceTypes = registrations.Where(item => item.Kind == kind
            && !staticTypes.Any(other => SymbolEqualityComparer.Default.Equals(other.Type, item.Type)));
        foreach (var (_, type) in instanceTypes)
        {
            code.Append("            if (instance.GetType() == ").Append(TypeExpression(type))
                .Append(")\n                return options.");
            if (kind == "activity")
                code.Append("AddAllActivities(").Append(TypeExpression(type)).Append(", instance);\n");
            else
                code.Append("AddNexusService(instance);\n");
        }
        code.Append("            throw new global::System.ArgumentException(\"Instance type is not a discovered ")
            .Append(kind)
            .Append(" type. Preserve explicit native registration for other types.\", nameof(instance));\n        }\n");
    }
}
