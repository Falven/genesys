package main

import (
	"fmt"
	"go/format"
	"go/types"
	"path/filepath"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"
)

func groupName(c candidate) string {
	name := "RegisterGenesys"
	if c.Service {
		return name + c.Object.Name()
	}
	if c.Receiver != nil {
		t := types.Unalias(c.Receiver)
		if ptr, ok := t.(*types.Pointer); ok {
			t = types.Unalias(ptr.Elem())
		}
		if n, ok := t.(*types.Named); ok {
			return name + n.Obj().Name()
		}
	}
	return name
}

func (a *analyzer) generate(p *packages.Package, cs []candidate) {
	sort.Slice(cs, func(i, j int) bool { return cs[i].Definition.Symbol < cs[j].Definition.Symbol })
	imports := map[string]string{"go.temporal.io/sdk/worker": "gsysworker"}
	qualifier := func(pkg *types.Package) string {
		if pkg.Path() == p.PkgPath {
			return ""
		}
		if alias, ok := imports[pkg.Path()]; ok {
			return alias
		}
		alias := fmt.Sprintf("gsys%d", len(imports))
		imports[pkg.Path()] = alias
		return alias
	}
	groups := map[string][]candidate{}
	for _, c := range cs {
		group := "RegisterGenesys"
		if c.Service {
			group += c.Object.Name()
		} else if c.Receiver != nil {
			t := types.Unalias(c.Receiver)
			if ptr, ok := t.(*types.Pointer); ok {
				t = types.Unalias(ptr.Elem())
			}
			n, ok := t.(*types.Named)
			if !ok {
				a.report("go.receiver-unresolved", "warning", "Receiver type needs explicit native assembly.", c.Definition.Source)
				continue
			}
			group += n.Obj().Name()
		}
		groups[group] = append(groups[group], c)
	}
	groupNames := []string{}
	for name := range groups {
		groupNames = append(groupNames, name)
	}
	sort.Strings(groupNames)
	var functions strings.Builder
	for _, name := range groupNames {
		group := groups[name]
		params := []string{"registry gsysworker.Registry"}
		lines := []string{}
		names := map[string]location{}
		receiverAdded := false
		if existing := p.Types.Scope().Lookup(name); existing != nil && !strings.HasSuffix(a.loc(p.Fset, existing.Pos()).Path, "zz_genesys_registration.go") {
			a.output.Emission.Diagnostics = append(a.output.Emission.Diagnostics, diagnostic{"go.generated-symbol-collision", "error", "Authored symbol conflicts with generated " + name, a.loc(p.Fset, existing.Pos())})
		}
		for _, c := range group {
			expression := c.Expression
			if c.Service {
				imports["github.com/nexus-rpc/sdk-go/nexus"] = "gsysnexus"
				params = append(params, "service *gsysnexus.Service")
				expression = "service"
			} else if c.Receiver != nil {
				if !receiverAdded {
					t := c.Receiver
					if _, ok := types.Unalias(t).(*types.Pointer); !ok {
						t = types.NewPointer(t)
					}
					params = append(params, "instance "+types.TypeString(t, qualifier))
					receiverAdded = true
				}
				expression = "instance." + c.Expression
			}
			key := c.Definition.Kind + ":" + c.Definition.Identity.Name
			if c.Definition.Identity.State == "resolved" {
				if prev, ok := names[key]; ok {
					a.output.Emission.Diagnostics = append(a.output.Emission.Diagnostics, diagnostic{"go.generated-name-collision", "error", fmt.Sprintf("Duplicate native name %s in %s (also %s:%d). Use explicit native assembly for this scope.", key, name, prev.Path, prev.Line), c.Definition.Source})
				}
				names[key] = c.Definition.Source
			}
			method := map[string]string{"workflow": "RegisterWorkflow", "activity": "RegisterActivity", "nexus": "RegisterNexusService"}[c.Definition.Kind]
			lines = append(lines, "registry."+method+"("+expression+")")
		}
		functions.WriteString("// " + name + " registers native definitions using application-owned dependencies.\nfunc " + name + "(" + strings.Join(params, ", ") + ") {\n" + strings.Join(lines, "\n") + "\n}\n\n")
	}
	var b strings.Builder
	b.WriteString("// Code generated by Genesys. DO NOT EDIT.\npackage " + p.Name + "\n\nimport (\n")
	paths := []string{}
	for path := range imports {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		fmt.Fprintf(&b, "%s %q\n", imports[path], path)
	}
	b.WriteString(")\n\n" + functions.String())
	content, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}
	path := filepath.ToSlash(filepath.Join(filepath.Dir(cs[0].Definition.Source.Path), "zz_genesys_registration.go"))
	a.output.Emission.Artifacts = append(a.output.Emission.Artifacts, artifact{path, string(content), "registration"})
}

func (a *analyzer) generateAggregates(pkgs []*packages.Package, candidates map[*packages.Package][]candidate, entries map[string]entry) {
	roots := map[string]map[*packages.Package][]candidate{}
	for _, p := range pkgs {
		for _, c := range candidates[p] {
			r := entries[c.Definition.EntryID].DiscoveryRoot
			if roots[r] == nil {
				roots[r] = map[*packages.Package][]candidate{}
			}
			roots[r][p] = append(roots[r][p], c)
		}
	}
	rootNames := []string{}
	for r := range roots {
		rootNames = append(rootNames, r)
	}
	sort.Strings(rootNames)
	for _, r := range rootNames {
		imports := map[string]string{"go.temporal.io/sdk/worker": "gsysworker"}
		params := []string{"registry gsysworker.Registry"}
		calls := []string{}
		comments := []string{}
		names := map[string]definition{}
		qualifier := func(pkg *types.Package) string {
			if alias, ok := imports[pkg.Path()]; ok {
				return alias
			}
			alias := fmt.Sprintf("gsys%d", len(imports))
			imports[pkg.Path()] = alias
			return alias
		}
		for _, p := range pkgs {
			cs := roots[r][p]
			if len(cs) == 0 {
				continue
			}
			if p.Name == "main" {
				a.report("go.aggregate-main-package", "warning", "Go main packages cannot be imported by aggregate registration. Use generated package-local helpers in explicit native assembly.", cs[0].Definition.Source)
				continue
			}
			internalPrefix := ""
			if index := strings.LastIndex(p.PkgPath, "/internal/"); index >= 0 {
				internalPrefix = p.PkgPath[:index]
			}
			aggregateImport := ""
			if p.Module != nil {
				aggregateImport = p.Module.Path + "/" + relative(p.Module.Dir, filepath.Join(a.root, r, "gsysregistration"))
			}
			if internalPrefix != "" && !strings.HasPrefix(aggregateImport, internalPrefix+"/") {
				a.report("go.aggregate-internal-package", "warning", "Native internal-package visibility requires explicit package-local registration; aggregate import would be invalid.", cs[0].Definition.Source)
				continue
			}
			groups := map[string][]candidate{}
			for _, c := range cs {
				groups[groupName(c)] = append(groups[groupName(c)], c)
			}
			groupNames := []string{}
			for name := range groups {
				groupNames = append(groupNames, name)
			}
			sort.Strings(groupNames)
			for _, name := range groupNames {
				group := groups[name]
				first := group[0]
				arguments := []string{"registry"}
				parameter := ""
				if first.Service {
					imports["github.com/nexus-rpc/sdk-go/nexus"] = "gsysnexus"
					parameter = fmt.Sprintf("service%d", len(params))
					params = append(params, parameter+" *gsysnexus.Service")
					comments = append(comments, "// "+parameter+" is constructed by "+first.Definition.Symbol+".")
				} else if first.Receiver != nil {
					t := types.Unalias(first.Receiver)
					if ptr, ok := t.(*types.Pointer); ok {
						t = types.Unalias(ptr.Elem())
					}
					named, ok := t.(*types.Named)
					if !ok || !named.Obj().Exported() {
						a.report("go.aggregate-private-receiver", "warning", "This receiver type cannot be named outside its package. Use the package-local generated helper with its application-owned instance.", first.Definition.Source)
						continue
					}
					parameter = fmt.Sprintf("instance%d", len(params))
					params = append(params, parameter+" "+types.TypeString(types.NewPointer(t), qualifier))
					comments = append(comments, "// "+parameter+" supplies "+first.Definition.Construction.Symbol+".")
				}
				if parameter != "" {
					arguments = append(arguments, parameter)
				}
				alias := qualifier(p.Types)
				calls = append(calls, alias+"."+name+"("+strings.Join(arguments, ", ")+")")
				for _, c := range group {
					if c.Definition.Identity.State != "resolved" {
						continue
					}
					key := c.Definition.Kind + ":" + c.Definition.Identity.Name
					if prev, ok := names[key]; ok {
						a.report("go.aggregate-name-collision", "warning", fmt.Sprintf("Aggregate registration repeats %s from %s. Use package-local helpers on separate native registries or explicit scoped overrides.", key, prev.Symbol), c.Definition.Source)
					}
					names[key] = c.Definition
				}
			}
		}
		if len(calls) == 0 {
			continue
		}
		var b strings.Builder
		b.WriteString("// Code generated by Genesys. DO NOT EDIT.\npackage gsysregistration\n\nimport (\n")
		paths := []string{}
		for path := range imports {
			paths = append(paths, path)
		}
		sort.Strings(paths)
		for _, path := range paths {
			fmt.Fprintf(&b, "%s %q\n", imports[path], path)
		}
		b.WriteString(")\n\n// Register registers all discovered Go packages on this native registry.\n// Use package-local helpers when native registration scopes must differ.\n" + strings.Join(comments, "\n") + "\nfunc Register(" + strings.Join(params, ", ") + ") {\n" + strings.Join(calls, "\n") + "\n}\n")
		content, err := format.Source([]byte(b.String()))
		if err != nil {
			panic(err)
		}
		a.output.Emission.Artifacts = append(a.output.Emission.Artifacts, artifact{filepath.ToSlash(filepath.Join(r, "gsysregistration", "registration.go")), string(content), "registration"})
	}
}
