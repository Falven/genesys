const slash = (path: string) => path.replaceAll("\\", "/");
const sourceExtension = /\.[cm]?[jt]sx?$/;
const inside = (root: string, path: string) => {
  const child = slash(relative(root, path));
  return !isAbsolute(child) && child !== ".." && !child.startsWith("../");
};
const generated = "// Code generated by Genesys. Do not edit.\n";

interface Model {
  program: ts.Program;
  checker: ts.TypeChecker;
  config?: string;
  parsed: ts.ParsedCommandLine;
}

function location(context: AnalysisContext, node: ts.Node): SourceLocation {
  const file = node.getSourceFile();
  const point = file.getLineAndCharacterOfPosition(node.getStart(file));
  return {
    path: slash(relative(context.projectRoot, file.fileName)),
    line: point.line + 1,
    column: point.character + 1,
  };
}

function model(context: AnalysisContext, entry: SourceEntry, diagnostics: Diagnostic[]): Model {
  const root = resolve(context.projectRoot, context.package.root);
  const config = ts.findConfigFile(
    dirname(resolve(context.projectRoot, entry.path)),
    ts.sys.fileExists,
  );
  let parsed: ts.ParsedCommandLine;
  if (config) {
    const result = ts.readConfigFile(config, ts.sys.readFile);
    if (result.error) diagnostics.push(compilerDiagnostic(context, result.error));
    parsed = ts.parseJsonConfigFileContent(
      result.config ?? {},
      ts.sys,
      dirname(config),
      undefined,
      config,
    );
    diagnostics.push(...parsed.errors.map((error) => compilerDiagnostic(context, error)));
  } else {
    parsed = {
      options: {
        target: ts.ScriptTarget.ESNext,
        module: ts.ModuleKind.NodeNext,
        moduleResolution: ts.ModuleResolutionKind.NodeNext,
        allowJs: true,
        noEmit: true,
      },
      fileNames: [...context.sources.keys()]
        .filter(
          (path) =>
            sourceExtension.test(path) &&
            (context.package.root === "." || path.startsWith(`${context.package.root}/`)),
        )
        .map((path) => resolve(context.projectRoot, path)),
      errors: [],
    };
    diagnostics.push({
      code: "typescript.no-tsconfig",
      severity: "warning",
      source: { path: entry.path },
      message:
        "No tsconfig.json was found. Static analysis uses NodeNext resolution; TypeScript Worker builds need native package build settings.",
    });
  }
  const host = ts.createCompilerHost(parsed.options);
  const originalRead = host.readFile;
  host.readFile = (path) =>
    context.sources.get(slash(relative(context.projectRoot, path))) ?? originalRead(path);
  host.getCurrentDirectory = () => root;
  const program = ts.createProgram({
    rootNames: parsed.fileNames,
    options: parsed.options,
    host,
    projectReferences: parsed.projectReferences,
  });
  return { program, checker: program.getTypeChecker(), config, parsed };
}

function compilerDiagnostic(context: AnalysisContext, error: ts.Diagnostic): Diagnostic {
  return {
    code: `typescript.TS${error.code}`,
    severity: error.category === ts.DiagnosticCategory.Error ? "error" : "warning",
    message: ts.flattenDiagnosticMessageText(error.messageText, "\n"),
    ...(error.file
      ? {
          source: {
            path: slash(relative(context.projectRoot, error.file.fileName)),
            line: error.file.getLineAndCharacterOfPosition(error.start ?? 0).line + 1,
          },
        }
      : {}),
  };
}

function symbol(checker: ts.TypeChecker, node: ts.Node): ts.Symbol | undefined {
  let found =
    ts.isIdentifier(node) && ts.isShorthandPropertyAssignment(node.parent)
      ? checker.getShorthandAssignmentValueSymbol(node.parent)
      : checker.getSymbolAtLocation(node);
  if (found && found.flags & ts.SymbolFlags.Alias) found = checker.getAliasedSymbol(found);
  return found;
}

function unwrap(node: ts.Expression): ts.Expression {
  while (
    ts.isParenthesizedExpression(node) ||
    ts.isAsExpression(node) ||
    ts.isTypeAssertionExpression(node) ||
    ts.isSatisfiesExpression(node) ||
    ts.isNonNullExpression(node)
  )
    node = node.expression;
  return node;
}

function value(
  checker: ts.TypeChecker,
  expression: ts.Expression,
  seen = new Set<ts.Node>(),
): ts.Expression {
  const node = unwrap(expression);
  if (seen.has(node)) return node;
  seen.add(node);
  if (ts.isIdentifier(node) || ts.isPropertyAccessExpression(node)) {
    const declaration = symbol(
      checker,
      ts.isPropertyAccessExpression(node) ? node.name : node,
    )?.valueDeclaration;
    if (
      declaration &&
      ts.isVariableDeclaration(declaration) &&
      declaration.initializer &&
      ts.isVariableDeclarationList(declaration.parent) &&
      declaration.parent.flags & ts.NodeFlags.Const
    ) {
      return value(checker, declaration.initializer, seen);
    }
  }
  return node;
}

function literal(checker: ts.TypeChecker, expression?: ts.Expression): string | undefined {
  if (!expression) return;
  const node = value(checker, expression);
  if (ts.isStringLiteralLike(node)) return node.text;
  const type = checker.getTypeAtLocation(node);
  if (type.isStringLiteral()) return type.value;
  return;
}

function propertyName(checker: ts.TypeChecker, name: ts.PropertyName): string | undefined {
  if (ts.isIdentifier(name) || ts.isStringLiteralLike(name) || ts.isNumericLiteral(name))
    return name.text;
  if (ts.isComputedPropertyName(name)) return literal(checker, name.expression);
  return;
}

function native(
  checker: ts.TypeChecker,
  node: ts.Expression,
  packageName: string,
  exportName: string,
): boolean {
  const found = symbol(checker, ts.isPropertyAccessExpression(node) ? node.name : node);
  if (
    found?.name === exportName &&
    found.declarations?.some(
      (d) =>
        slash(d.getSourceFile().fileName).includes(`/node_modules/${packageName}/`) ||
        slash(d.getSourceFile().fileName).includes(
          `/node_modules/.pnpm/${packageName.replace("/", "+")}@`,
        ),
    )
  )
    return true;
  // Imported names are still identifiable when dependency declarations have not been installed.
  const local = checker.getSymbolAtLocation(
    ts.isPropertyAccessExpression(node) ? node.expression : node,
  );
  return !!local?.declarations?.some((declaration) => {
    if (ts.isImportSpecifier(declaration)) {
      const importNode = declaration.parent.parent.parent;
      return (
        ts.isStringLiteral(importNode.moduleSpecifier) &&
        importNode.moduleSpecifier.text === packageName &&
        (declaration.propertyName ?? declaration.name).text === exportName
      );
    }
    if (ts.isBindingElement(declaration) && ts.isVariableDeclaration(declaration.parent.parent)) {
      const initializer = declaration.parent.parent.initializer;
      return (
        !!initializer &&
        ts.isCallExpression(initializer) &&
        ts.isIdentifier(initializer.expression) &&
        initializer.expression.text === "require" &&
        literal(checker, initializer.arguments[0]) === packageName &&
        (declaration.propertyName ?? declaration.name).getText() === exportName
      );
    }
    if (
      ts.isVariableDeclaration(declaration) &&
      declaration.initializer &&
      ts.isPropertyAccessExpression(node)
    ) {
      const initializer = unwrap(declaration.initializer);
      if (
        ts.isCallExpression(initializer) &&
        ts.isIdentifier(initializer.expression) &&
        initializer.expression.text === "require" &&
        literal(checker, initializer.arguments[0]) === packageName &&
        node.name.text === exportName
      )
        return true;
    }
    if (ts.isNamespaceImport(declaration) && ts.isPropertyAccessExpression(node)) {
      const importNode = declaration.parent.parent;
      return (
        ts.isStringLiteral(importNode.moduleSpecifier) &&
        importNode.moduleSpecifier.text === packageName &&
        node.name.text === exportName
      );
    }
    return false;
  });
}

function objectProperties(
  checker: ts.TypeChecker,
  expression: ts.Expression,
  unresolved: (node: ts.Node) => void,
  seen = new Set<ts.Node>(),
): Map<string, ts.Node> {
  const node = value(checker, expression);
  const result = new Map<string, ts.Node>();
  if (seen.has(node)) {
    unresolved(node);
    return result;
  }
  seen.add(node);
  if (ts.isObjectLiteralExpression(node)) {
    for (const property of node.properties) {
      if (ts.isSpreadAssignment(property)) {
        for (const [name, implementation] of objectProperties(
          checker,
          property.expression,
          unresolved,
          new Set(seen),
        ))
          result.set(name, implementation);
      } else {
        const name = propertyName(checker, property.name);
        if (name === undefined) {
          unresolved(property);
          continue;
        }
        result.set(
          name,
          ts.isPropertyAssignment(property)
            ? property.initializer
            : ts.isShorthandPropertyAssignment(property)
              ? property.name
              : property,
        );
      }
    }
  } else {
    const type = checker.getTypeAtLocation(node);
    if (type.getSymbol()?.flags && type.getSymbol()!.flags & ts.SymbolFlags.Class) {
      unresolved(node);
      return result;
    }
    if (type.flags & (ts.TypeFlags.Any | ts.TypeFlags.Unknown) || type.getStringIndexType())
      unresolved(node);
    for (const member of type.getProperties()) {
      const declaration = member.valueDeclaration ?? member.declarations?.[0];
      if (declaration && checker.getTypeOfSymbolAtLocation(member, node).getCallSignatures().length)
        result.set(member.name, declaration);
    }
    if (!result.size) unresolved(node);
  }
  return result;
}

function callable(checker: ts.TypeChecker, node: ts.Node): boolean {
  return checker.getTypeAtLocation(node).getCallSignatures().length > 0;
}

function serviceName(checker: ts.TypeChecker, expression: ts.Expression): string | undefined {
  const node = value(checker, expression);
  if (
    (ts.isNewExpression(node) && native(checker, node.expression, "nexus-rpc", "ServiceHandler")) ||
    (ts.isCallExpression(node) && native(checker, node.expression, "nexus-rpc", "serviceHandler"))
  ) {
    const service = node.arguments?.[0];
    if (!service) return;
    const definition = value(checker, service);
    if (
      (ts.isCallExpression(definition) &&
        native(checker, definition.expression, "nexus-rpc", "service")) ||
      (ts.isCallExpression(definition) &&
        native(checker, definition.expression, "nexus-rpc", "defineService"))
    ) {
      const options = definition.arguments[0];
      if (options && native(checker, definition.expression, "nexus-rpc", "service"))
        return literal(checker, options);
      if (options) {
        const name = objectProperties(checker, options, () => {}).get("name");
        if (name && ts.isExpression(name)) return literal(checker, name);
      }
    }
    const type = checker.getTypeAtLocation(service);
    const name = type.getProperty("name");
    if (name) {
      const nameType = checker.getTypeOfSymbolAtLocation(name, service);
      if (nameType.isStringLiteral()) return nameType.value;
    }
  }
  return;
}

function isService(checker: ts.TypeChecker, node: ts.Expression): boolean {
  const expression = value(checker, node);
  return (
    ((ts.isNewExpression(expression) || ts.isCallExpression(expression)) &&
      (native(checker, expression.expression, "nexus-rpc", "ServiceHandler") ||
        native(checker, expression.expression, "nexus-rpc", "serviceHandler"))) ||
    !!checker
      .getTypeAtLocation(node)
      .getSymbol()
      ?.declarations?.some(
        (declaration) =>
          slash(declaration.getSourceFile().fileName).includes("/nexus-rpc/") &&
          ts.isClassDeclaration(declaration) &&
          declaration.name?.text === "ServiceHandler",
      )
  );
}

function findOptions(checker: ts.TypeChecker, expression: ts.Expression): Map<string, ts.Node> {
  return objectProperties(checker, expression, () => {});
}

function bundleSource(current: Model, expression: ts.Expression): ts.SourceFile | undefined {
  const node = value(current.checker, expression);
  let specifier: string | undefined;
  if (
    ts.isCallExpression(node) &&
    ts.isPropertyAccessExpression(node.expression) &&
    ts.isIdentifier(node.expression.expression) &&
    node.expression.expression.text === "require" &&
    node.expression.name.text === "resolve"
  )
    specifier = literal(current.checker, node.arguments[0]);
  if (
    ts.isCallExpression(node) &&
    node.arguments[0] &&
    native(current.checker, node.expression, "node:url", "fileURLToPath")
  )
    return bundleSource(current, node.arguments[0]);
  if (
    ts.isNewExpression(node) &&
    ts.isIdentifier(node.expression) &&
    node.expression.text === "URL" &&
    node.arguments?.[1]?.getText() === "import.meta.url"
  )
    specifier = literal(current.checker, node.arguments[0]);
  if (!specifier) return;
  const resolved = ts.resolveModuleName(
    specifier,
    node.getSourceFile().fileName,
    current.parsed.options,
    ts.sys,
  ).resolvedModule;
  if (resolved) return current.program.getSourceFile(resolved.resolvedFileName);
  return;
}

function sandboxImports(
  context: AnalysisContext,
  current: Model,
  file: ts.SourceFile,
  diagnostics: Diagnostic[],
  seen = new Set<string>(),
): void {
  if (seen.has(file.fileName)) return;
  seen.add(file.fileName);
  for (const statement of file.statements) {
    if (!ts.isImportDeclaration(statement) && !ts.isExportDeclaration(statement)) continue;
    if (!statement.moduleSpecifier || !ts.isStringLiteral(statement.moduleSpecifier)) continue;
    if (
      ts.isImportDeclaration(statement) &&
      (statement.importClause?.isTypeOnly ||
        (statement.importClause?.namedBindings &&
          ts.isNamedImports(statement.importClause.namedBindings) &&
          !statement.importClause.name &&
          statement.importClause.namedBindings.elements.length > 0 &&
          statement.importClause.namedBindings.elements.every((element) => element.isTypeOnly)))
    )
      continue;
    if (
      ts.isExportDeclaration(statement) &&
      (statement.isTypeOnly ||
        (statement.exportClause &&
          ts.isNamedExports(statement.exportClause) &&
          statement.exportClause.elements.length > 0 &&
          statement.exportClause.elements.every((element) => element.isTypeOnly)))
    )
      continue;
    const resolved = ts.resolveModuleName(
      statement.moduleSpecifier.text,
      file.fileName,
      current.parsed.options,
      ts.sys,
    ).resolvedModule;
    if (!resolved) continue;
    const source = current.program.getSourceFile(resolved.resolvedFileName);
    if (!source || source.isDeclarationFile) continue;
    const path = slash(relative(context.projectRoot, source.fileName));
    if (
      context.entries.some(
        (entry) =>
          entry.path === path &&
          (entry.role === "activity" || entry.role === "nexus" || entry.role === "worker"),
      )
    ) {
      diagnostics.push({
        code: "typescript.workflow-runtime-import",
        severity: "error",
        source: location(context, statement),
        related: [{ path }],
        message:
          "Workflow code imports a Worker, Activity, or Nexus implementation at runtime. Use type-only Activity imports and native Workflow proxies to keep the Workflow bundle sandboxed.",
      });
    } else sandboxImports(context, current, source, diagnostics, seen);
  }
}

function outputPath(model: Model, input: string): string | undefined {
  if (model.parsed.options.noEmit || model.parsed.options.emitDeclarationOnly) return;
  try {
    return ts
      .getOutputFileNames(model.parsed, input, !ts.sys.useCaseSensitiveFileNames)
      .find((path) => /\.[cm]?jsx?$/.test(path));
  } catch {
    return;
  }
}

function workerPrograms(
  context: AnalysisContext,
  models: Map<string, Model>,
  diagnostics: Diagnostic[],
): WorkerProgram[] {
  const groups = new Map<string, SourceEntry[]>();
  for (const entry of context.entries.filter(
    (entry) => entry.role === "worker" && entry.workerName,
  )) {
    const group = groups.get(entry.workerName!) ?? [];
    group.push(entry);
    groups.set(entry.workerName!, group);
  }
  const manifestPath = context.package.manifests.find((path) => path.endsWith("package.json"));
  const manifest = manifestPath ? JSON.parse(context.sources.get(manifestPath) ?? "{}") : {};
  const declared = [
    manifest.main,
    ...(typeof manifest.bin === "string" ? [manifest.bin] : Object.values(manifest.bin ?? {})),
  ].filter((path): path is string => typeof path === "string");
  const programs: WorkerProgram[] = [];
  for (const [name, entries] of groups) {
    const declaredEntries = entries.filter((entry) => {
      const input = resolve(context.projectRoot, entry.path);
      const output = outputPath(models.get(entry.path)!, input);
      return declared.some((path) =>
        [input, output].includes(resolve(context.projectRoot, context.package.root, path)),
      );
    });
    const candidates = declaredEntries.length
      ? declaredEntries
      : entries.filter((entry) => {
          const current = models.get(entry.path)!;
          const input = resolve(context.projectRoot, entry.path);
          const output = outputPath(current, input);
          if (
            declared.some((path) =>
              [input, output].includes(resolve(context.projectRoot, context.package.root, path)),
            )
          )
            return true;
          const file = current.program.getSourceFile(input);
          return (
            file?.statements.some(
              (statement) =>
                ts.isExpressionStatement(statement) &&
                (ts.isCallExpression(unwrap(statement.expression)) ||
                  ts.isAwaitExpression(unwrap(statement.expression))),
            ) ?? false
          );
        });
    const source = candidates[0] ?? entries[0]!;
    const current = models.get(source.path)!;
    const program: WorkerProgram = {
      id: `typescript:${context.package.id}:${name}`,
      name,
      language: "typescript",
      packageId: context.package.id,
      source: { path: source.path },
      readiness: {
        state: "unavailable",
        description:
          "Native Worker heartbeats and process-attributed successful polls are required. RUNNING and process startup do not prove readiness; dynamic Worker instance coverage and native retirement remain unknown.",
        evidence: [
          "Worker heartbeat host/PID/start time",
          "WorkerPollerInfo.last_successful_poll_time",
          "Native deployment drainage separately from readiness",
        ],
      },
    };
    const cwd = context.package.root;
    const packageManager =
      typeof manifest.packageManager === "string" ? manifest.packageManager.split("@")[0] : "npm";
    if (manifest.scripts?.build && ["npm", "pnpm", "yarn", "bun"].includes(packageManager)) {
      program.build = [{ executable: packageManager, args: ["run", "build"], cwd }];
    } else if (
      current.config &&
      !current.parsed.options.noEmit &&
      !current.parsed.options.emitDeclarationOnly
    ) {
      let directory = resolve(context.projectRoot, cwd);
      let tsc: string | undefined;
      while (inside(context.projectRoot, directory)) {
        const candidate = join(directory, "node_modules/typescript/bin/tsc");
        if (ts.sys.fileExists(candidate)) {
          tsc = candidate;
          break;
        }
        const parent = dirname(directory);
        if (parent === directory) break;
        directory = parent;
      }
      if (tsc)
        program.build = [
          {
            executable: "node",
            args: [
              slash(relative(resolve(context.projectRoot, cwd), tsc)),
              "--build",
              slash(relative(resolve(context.projectRoot, cwd), current.config)),
            ],
            cwd,
          },
        ];
      else
        diagnostics.push({
          code: "typescript.compiler-unavailable",
          severity: "warning",
          source: { path: source.path },
          message:
            "Install the package's TypeScript compiler or provide its native build script. Genesys does not choose an application compiler version.",
        });
    }
    if (candidates.length === 1) {
      const input = resolve(context.projectRoot, source.path);
      const output = outputPath(current, input);
      const script = /\.[cm]?js$/.test(source.path) && !output ? input : output;
      if (script && inside(context.projectRoot, script) && (script === input || program.build))
        program.start = {
          executable: "node",
          args: [slash(relative(resolve(context.projectRoot, cwd), script))],
          cwd,
        };
      else
        diagnostics.push({
          code: "typescript.worker-output-unresolved",
          severity: "warning",
          source: { path: source.path },
          message:
            "Native Worker executable output is unresolved (no emit, custom bundler, or missing tsconfig). Use the native startup override; no source loader is assumed.",
        });
    } else
      diagnostics.push({
        code: "typescript.worker-entrypoint-ambiguous",
        severity: "warning",
        source: { path: source.path },
        related: candidates.map((entry) => ({ path: entry.path })),
        message: `Worker ${name} has ${candidates.length} executable candidates. Declare the native package main/bin or use a startup override.`,
      });
    programs.push(program);
  }
  return programs;
}

async function analyze(context: AnalysisContext): Promise<AnalysisResult> {
  const diagnostics: Diagnostic[] = [];
  const definitions: Definition[] = [];
  const models = new Map<string, Model>();
  const byConfig = new Map<string, Model>();
  for (const entry of context.entries) {
    const config =
      ts.findConfigFile(dirname(resolve(context.projectRoot, entry.path)), ts.sys.fileExists) ?? "";
    let current = byConfig.get(config);
    if (!current) {
      current = model(context, entry, diagnostics);
      byConfig.set(config, current);
    }
    models.set(entry.path, current);
  }
  const messageHandlers = new Set<string>();
  const handlerKey = (node: ts.Node): string => `${node.getSourceFile().fileName}:${node.pos}`;
  for (const { checker, program } of byConfig.values()) {
    const markHandler = (expression: ts.Expression): void => {
      const resolved = value(checker, expression);
      if (ts.isConditionalExpression(resolved)) {
        markHandler(resolved.whenTrue);
        markHandler(resolved.whenFalse);
      }
      for (const reference of [unwrap(expression), resolved]) {
        const target = symbol(
          checker,
          ts.isPropertyAccessExpression(reference) ? reference.name : reference,
        );
        for (const declaration of target?.declarations ?? [])
          messageHandlers.add(handlerKey(declaration));
        if (ts.isArrowFunction(reference) || ts.isFunctionExpression(reference)) {
          messageHandlers.add(handlerKey(reference));
          if (ts.isVariableDeclaration(reference.parent))
            messageHandlers.add(handlerKey(reference.parent));
        }
      }
      if (ts.isIdentifier(resolved) && resolved.text === "undefined") return;
      const target = symbol(
        checker,
        ts.isPropertyAccessExpression(resolved) ? resolved.name : resolved,
      );
      const declaration = target?.valueDeclaration;
      if (
        !ts.isArrowFunction(resolved) &&
        !ts.isFunctionExpression(resolved) &&
        (!declaration ||
          (!ts.isFunctionDeclaration(declaration) && !ts.isMethodDeclaration(declaration)))
      ) {
        diagnostics.push({
          code: "typescript.message-handler-unresolved",
          severity: "warning",
          source: location(context, expression),
          message:
            "Native message handler or validator is not a unique static function. Referenced exports are excluded from automatic registration; retain explicit native assembly.",
        });
      }
    };
    for (const file of program.getSourceFiles()) {
      if (
        file.isDeclarationFile ||
        !context.sources.has(slash(relative(context.projectRoot, file.fileName)))
      )
        continue;
      const visit = (node: ts.Node): void => {
        if (
          ts.isCallExpression(node) &&
          native(checker, value(checker, node.expression), "@temporalio/workflow", "setHandler")
        ) {
          if (node.arguments[1]) markHandler(node.arguments[1]);
          const options = node.arguments[2];
          if (options) {
            const properties = objectProperties(checker, options, (unresolved) =>
              diagnostics.push({
                code: "typescript.message-options-unresolved",
                severity: "warning",
                source: location(context, unresolved),
                message:
                  "Native handler options are dynamic; validator references require explicit native assembly.",
              }),
            );
            const validator = properties.get("validator");
            if (validator && ts.isExpression(validator)) markHandler(validator);
          }
        }
        ts.forEachChild(node, visit);
      };
      visit(file);
    }
  }
  const nativeAssembly = new Set<string>();
  const manifestPath = context.package.manifests.find((path) => path.endsWith("package.json"));
  const manifest = manifestPath ? JSON.parse(context.sources.get(manifestPath) ?? "{}") : {};
  let installedSdk: string | undefined;
  const firstModel = byConfig.values().next().value as Model | undefined;
  const firstEntry = context.entries[0];
  if (firstModel && firstEntry) {
    const dependency = ts.resolveModuleName(
      "@temporalio/worker",
      resolve(context.projectRoot, firstEntry.path),
      firstModel.parsed.options,
      ts.sys,
    ).resolvedModule;
    if (dependency) {
      let directory = dirname(dependency.resolvedFileName);
      while (dirname(directory) !== directory) {
        const text = ts.sys.readFile(join(directory, "package.json"));
        if (text) {
          const metadata = JSON.parse(text);
          if (metadata.name === "@temporalio/worker") {
            installedSdk = metadata.version;
            break;
          }
        }
        directory = dirname(directory);
      }
    }
  }
  const requestedSdk =
    manifest.dependencies?.["@temporalio/worker"] ??
    manifest.devDependencies?.["@temporalio/worker"];
  diagnostics.push({
    code: "typescript.sdk-version",
    severity: "info",
    source: { path: manifestPath ?? context.package.root },
    message: `Declared @temporalio/worker: ${typeof requestedSdk === "string" ? requestedSdk : "not declared in this package"}; installed: ${installedSdk ?? "unresolved"}. Registration APIs reviewed against released SDK 1.25.0 and nexus-rpc 0.0.3. Static analysis uses TypeScript 6.0.3; native build validation uses the application's own compiler.`,
  });
  for (const current of byConfig.values()) {
    const { checker, program } = current;
    const fileEntries = new Map(
      context.entries.map((entry) => [resolve(context.projectRoot, entry.path), entry]),
    );
    for (const file of program.getSourceFiles()) {
      if (file.isDeclarationFile || !fileEntries.has(file.fileName)) continue;
      const entry = fileEntries.get(file.fileName)!;
      if (models.get(entry.path) !== current) continue;
      const visit = (node: ts.Node): void => {
        if (
          ts.isCallExpression(node) &&
          ts.isPropertyAccessExpression(node.expression) &&
          node.expression.name.text === "create" &&
          native(checker, node.expression.expression, "@temporalio/worker", "Worker")
        ) {
          const scope = `${entry.path}:${node.getStart(file)}`;
          const options = node.arguments[0];
          const properties = options ? findOptions(checker, options) : new Map<string, ts.Node>();
          if (!options || !ts.isObjectLiteralExpression(value(checker, options)))
            diagnostics.push({
              code: "typescript.worker-options-unresolved",
              severity: "warning",
              source: location(context, node),
              message:
                "Worker options come from dynamic native assembly. Registration and Worker instance coverage remain incomplete; application construction is not executed.",
            });
          const activities = properties.get("activities");
          if (activities && ts.isExpression(activities)) {
            const resolved = value(checker, activities);
            if (ts.isCallExpression(resolved)) {
              const factory = symbol(checker, resolved.expression);
              for (const declaration of factory?.declarations ?? [])
                nativeAssembly.add(`${declaration.getSourceFile().fileName}:${factory!.name}`);
            }
            const mapping = objectProperties(checker, activities, (unresolved) =>
              diagnostics.push({
                code: "typescript.native-assembly-unresolved",
                severity: "warning",
                source: location(context, unresolved),
                message:
                  "Activity mapping is dynamic or has unknown keys. Keep its native assembly; static discovery cannot enumerate all registrations.",
              }),
            );
            for (const [name, implementation] of mapping) {
              const implementationSymbol =
                ts.isIdentifier(implementation) &&
                ts.isShorthandPropertyAssignment(implementation.parent)
                  ? (checker.getShorthandAssignmentValueSymbol(implementation.parent) ??
                    symbol(checker, implementation))
                  : symbol(checker, implementation);
              const declaration = implementationSymbol?.valueDeclaration ?? implementation;
              const owner = fileEntries.get(declaration.getSourceFile().fileName) ?? entry;
              if (callable(checker, implementation) || ts.isMethodDeclaration(implementation))
                definitions.push({
                  id: `${scope}:activity:${name}`,
                  source: location(context, implementation),
                  entryId: owner.id,
                  language: "typescript",
                  kind: "activity",
                  symbol: implementation.getText(),
                  identity: { name, state: "resolved" },
                  registrationScope: scope,
                  construction: {
                    symbol: activities.getText(),
                    reason:
                      "Application-owned Worker activities mapping; preserve closures, bound receivers, and factory dependencies.",
                  },
                });
              else
                diagnostics.push({
                  code: "typescript.activity-not-callable",
                  severity: "warning",
                  source: location(context, implementation),
                  message: `Activity mapping value ${name} is not statically callable. The native SDK registers function values only; resolve its type to establish registration.`,
                });
            }
          }
          const workflowsPath = properties.get("workflowsPath");
          if (workflowsPath && ts.isExpression(workflowsPath)) {
            const bundle = bundleSource(current, workflowsPath);
            const bundleSymbol = bundle && checker.getSymbolAtLocation(bundle);
            if (bundle && bundleSymbol) {
              sandboxImports(context, current, bundle, diagnostics);
              for (const exported of checker.getExportsOfModule(bundleSymbol)) {
                const target =
                  exported.flags & ts.SymbolFlags.Alias
                    ? checker.getAliasedSymbol(exported)
                    : exported;
                const declaration = target.valueDeclaration ?? target.declarations?.[0];
                if (
                  !declaration ||
                  !checker.getTypeOfSymbolAtLocation(target, declaration).getCallSignatures().length
                )
                  continue;
                const owner =
                  fileEntries.get(declaration.getSourceFile().fileName) ??
                  fileEntries.get(bundle.fileName) ??
                  entry;
                definitions.push({
                  id: `${scope}:workflow:${exported.name}`,
                  source: location(context, declaration),
                  entryId: owner.id,
                  language: "typescript",
                  kind: "workflow",
                  symbol: exported.name,
                  identity:
                    exported.name === "default"
                      ? { state: "dynamic", reason: "Native default Workflow fallback." }
                      : { name: exported.name, state: "resolved" },
                  registrationScope: scope,
                });
              }
            } else
              diagnostics.push({
                code: "typescript.workflow-path-unresolved",
                severity: "warning",
                source: location(context, workflowsPath),
                message:
                  "Workflow module path cannot be resolved statically. Preserve the authored workflowsPath and native bundler configuration; its registration scope remains unresolved.",
              });
          }
          const services = properties.get("nexusServices");
          if (services && ts.isExpression(services)) {
            const array = value(checker, services);
            if (ts.isArrayLiteralExpression(array)) {
              for (const [index, service] of array.elements.entries()) {
                if (ts.isSpreadElement(service)) {
                  diagnostics.push({
                    code: "typescript.nexus-array-unresolved",
                    severity: "warning",
                    source: location(context, service),
                    message:
                      "Nexus service array spread requires native assembly; its complete service set is unresolved.",
                  });
                  continue;
                }
                const name = serviceName(checker, service);
                definitions.push({
                  id: `${scope}:nexus:${index}`,
                  source: location(context, service),
                  entryId: entry.id,
                  language: "typescript",
                  kind: "nexus",
                  symbol: service.getText(),
                  registrationScope: scope,
                  identity: name
                    ? { name, state: "resolved" }
                    : {
                        state: "unresolved",
                        reason:
                          "Native Nexus service identity is computed or supplied by application construction.",
                      },
                  construction: {
                    symbol: service.getText(),
                    reason: "Reuse the native service handler and its operation handlers.",
                  },
                });
              }
            } else
              diagnostics.push({
                code: "typescript.nexus-array-unresolved",
                severity: "warning",
                source: location(context, services),
                message:
                  "Nexus services are supplied dynamically. Keep native application assembly; static coverage is incomplete.",
              });
          }
          if (properties.has("workflowBundle"))
            diagnostics.push({
              code: "typescript.native-workflow-bundle",
              severity: "info",
              source: location(context, node),
              message:
                "Authored workflowBundle is preserved. Its exports and sandbox dependencies remain the responsibility of the native bundle build.",
            });
        }
        ts.forEachChild(node, visit);
      };
      visit(file);
    }
  }
  for (const entry of context.entries.filter((entry) => entry.role !== "worker")) {
    const current = models.get(entry.path)!;
    const { checker, program } = current;
    const file = program.getSourceFile(resolve(context.projectRoot, entry.path));
    if (!file) {
      diagnostics.push({
        code: "typescript.source-excluded",
        severity: "warning",
        source: { path: entry.path },
        message: "Native tsconfig excludes this source. No registration is generated.",
      });
      continue;
    }
    diagnostics.push(
      ...program.getSyntacticDiagnostics(file).map((error) => compilerDiagnostic(context, error)),
    );
    diagnostics.push(
      ...program
        .getSemanticDiagnostics(file)
        .filter((error) => [2308, 2307, 7016, 2792].includes(error.code))
        .map((error) => ({
          ...compilerDiagnostic(context, error),
          severity: error.code === 2308 ? ("error" as const) : ("warning" as const),
        })),
    );
    if (entry.role === "workflow") sandboxImports(context, current, file, diagnostics);
    const moduleSymbol = checker.getSymbolAtLocation(file);
    if (!moduleSymbol) {
      diagnostics.push({
        code: "typescript.no-module-exports",
        severity: "warning",
        source: { path: entry.path },
        message:
          "This file has no statically resolved module exports. Preserve explicit native assembly.",
      });
      continue;
    }
    for (const exported of checker.getExportsOfModule(moduleSymbol)) {
      const target =
        exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported;
      const declaration = target.valueDeclaration ?? target.declarations?.[0];
      if (!declaration || !(target.flags & ts.SymbolFlags.Value)) continue;
      if (nativeAssembly.has(`${declaration.getSourceFile().fileName}:${target.name}`)) continue;
      if (entry.role === "workflow") {
        const resolved =
          ts.isVariableDeclaration(declaration) && declaration.initializer
            ? value(checker, declaration.initializer)
            : undefined;
        const resolvedTarget = resolved
          ? symbol(checker, ts.isPropertyAccessExpression(resolved) ? resolved.name : resolved)
          : undefined;
        if (
          messageHandlers.has(handlerKey(declaration)) ||
          resolvedTarget?.declarations?.some((node) => messageHandlers.has(handlerKey(node))) ||
          (resolved && messageHandlers.has(handlerKey(resolved)))
        ) {
          diagnostics.push({
            code: "typescript.message-handler-excluded",
            severity: "info",
            source: location(context, declaration),
            message: `Export ${exported.name} is a native message handler or validator, not an automatic Workflow registration. Explicit native assembly remains available.`,
          });
          continue;
        }
      }
      const type = checker.getTypeOfSymbolAtLocation(target, declaration);
      const expression = ts.isVariableDeclaration(declaration)
        ? declaration.initializer
        : ts.isExportAssignment(declaration)
          ? declaration.expression
          : undefined;
      const name = exported.name;
      const base = {
        id: `${entry.id}:${entry.role}:${name}`,
        source: location(context, declaration),
        entryId: entry.id,
        language: "typescript" as const,
        symbol: name,
      };
      if (entry.role === "nexus") {
        if (expression && isService(checker, expression)) {
          const nativeName = serviceName(checker, expression);
          definitions.push({
            ...base,
            kind: "nexus",
            identity: nativeName
              ? { name: nativeName, state: "resolved" }
              : {
                  state: "unresolved",
                  reason:
                    "Nexus service name is not statically known; preserve its native service contract.",
                },
          });
        } else if (type.getCallSignatures().length || type.getConstructSignatures().length)
          diagnostics.push({
            code: "typescript.nexus-native-assembly",
            severity: "warning",
            source: location(context, declaration),
            message: `Export ${name} needs native service construction. Supply the existing ServiceHandler through Worker.nexusServices; Genesys does not invoke factories.`,
          });
      } else if (type.getCallSignatures().length) {
        definitions.push({
          ...base,
          kind: entry.role as "workflow" | "activity",
          identity:
            entry.role === "workflow" && name === "default"
              ? {
                  state: "dynamic",
                  reason:
                    "The default Workflow export is the native fallback for unknown Workflow types.",
                }
              : { name, state: "resolved" },
        });
      } else if (
        entry.role === "activity" &&
        expression &&
        (ts.isNewExpression(value(checker, expression)) ||
          (type.getSymbol()?.flags ?? 0) & ts.SymbolFlags.Class)
      ) {
        diagnostics.push({
          code: "typescript.activity-instance-required",
          severity: "warning",
          source: location(context, declaration),
          message: `Activity instance ${name} needs an explicit native function mapping. Prototype methods are not enumerable Activity registrations; Genesys does not bind methods or construct dependencies.`,
        });
      } else if (
        entry.role === "activity" &&
        expression &&
        !type.getConstructSignatures().length &&
        type
          .getProperties()
          .some(
            (member) =>
              checker.getTypeOfSymbolAtLocation(member, declaration).getCallSignatures().length,
          )
      ) {
        const mapping = objectProperties(checker, expression, (node) =>
          diagnostics.push({
            code: "typescript.activity-map-unresolved",
            severity: "warning",
            source: location(context, node),
            message: `Activity export ${name} has dynamic mapping keys. Keep its native assembly for entries that cannot be enumerated.`,
          }),
        );
        for (const [memberName, implementation] of mapping) {
          if (!callable(checker, implementation) && !ts.isMethodDeclaration(implementation))
            continue;
          definitions.push({
            ...base,
            id: `${base.id}:${memberName}`,
            kind: "activity",
            symbol: `${name}[${JSON.stringify(memberName)}]`,
            identity: { name: memberName, state: "resolved" },
            construction: {
              symbol: name,
              reason:
                "Existing exported Activity mapping; reuse its function values without constructing dependencies.",
            },
          });
        }
      } else if (entry.role === "activity" && type.getConstructSignatures().length) {
        diagnostics.push({
          code: "typescript.activity-instance-required",
          severity: "warning",
          source: location(context, declaration),
          message: `Activity class ${name} needs an application-owned instance and bound function mapping. Preserve native Worker assembly; constructor arguments are never generated.`,
        });
      } else if (type.flags & (ts.TypeFlags.Any | ts.TypeFlags.Unknown)) {
        diagnostics.push({
          code: "typescript.export-unresolved",
          severity: "warning",
          source: location(context, declaration),
          message: `Export ${name} has unresolved type information. Install native dependencies and resolve package imports or retain explicit native assembly.`,
        });
      }
    }
  }
  const scopes = new Map<string, Definition>();
  for (const definition of definitions) {
    if (!definition.registrationScope || !definition.identity.name) continue;
    const key = `${definition.registrationScope}:${definition.kind}:${definition.identity.name}`;
    const previous = scopes.get(key);
    if (previous)
      diagnostics.push({
        code: "typescript.native-registration-collision",
        severity: "error",
        source: definition.source,
        related: [previous.source],
        message: `Native ${definition.kind} identity ${definition.identity.name} is repeated in the same Worker registration scope.`,
      });
    scopes.set(key, definition);
  }
  const workers = workerPrograms(context, models, diagnostics);
  const uniqueDiagnostics = [
    ...new Map(diagnostics.map((item) => [JSON.stringify(item), item])).values(),
  ];
  return { definitions, diagnostics: uniqueDiagnostics, workers };
}

function importPath(from: string, to: string): string {
  let path = slash(relative(dirname(from), to));
  if (!path.startsWith(".")) path = `./${path}`;
  return path
    .replace(/\.mts$/, ".mjs")
    .replace(/\.cts$/, ".cjs")
    .replace(/\.tsx?$/, ".js");
}

async function emit(context: EmitContext): Promise<EmissionResult> {
  const artifacts: EmissionResult["artifacts"] = [];
  const diagnostics: Diagnostic[] = [];
  const roots = [
    ...new Set(
      context.entries
        .filter((entry) => entry.role !== "worker")
        .map((entry) => entry.discoveryRoot),
    ),
  ].sort();
  for (const root of roots) {
    // Beside source keeps rootDir, relative module resolution, and emitted paths native.
    for (const kind of ["workflow", "activity", "nexus"] as const) {
      const entries = context.entries.filter(
        (entry) => entry.discoveryRoot === root && entry.role === kind,
      );
      const definitions = [
        ...new Map(
          context.analysis.definitions
            .filter(
              (definition) =>
                !definition.registrationScope &&
                entries.some((entry) => entry.id === definition.entryId),
            )
            .map((definition) => [
              `${definition.identity.name ?? definition.symbol}:${definition.source.path}:${definition.source.line}:${definition.source.column}`,
              definition,
            ]),
        ).values(),
      ];
      const extension = entries.some((entry) => /\.m[jt]s$/.test(entry.path)) ? "mts" : "ts";
      const path = `${root}/genesys-${kind === "workflow" ? "workflows" : kind === "activity" ? "activities" : "nexus"}.${extension}`;
      const identities = new Map<string, Definition>();
      let collision = false;
      for (const definition of definitions) {
        const name =
          definition.identity.name ??
          (definition.identity.state === "dynamic" ? "default" : undefined);
        if (!name) continue;
        const previous = identities.get(name);
        if (previous) {
          collision = true;
          diagnostics.push({
            code: "typescript.generated-registration-collision",
            severity: "warning",
            source: definition.source,
            related: [previous.source],
            message: `Generated ${kind} collection ${path} has duplicate native identity ${name}. This aggregate is not emitted. Independent native Worker scopes can reuse names; preserve explicit native assembly or remove the ambiguous automatic export.`,
          });
        }
        identities.set(name, definition);
      }
      if (collision) continue;
      const lines = [generated.trimEnd()];
      const values: string[] = [];
      for (const [index, definition] of definitions.entries()) {
        const entry = entries.find((entry) => entry.id === definition.entryId)!;
        const module = JSON.stringify(importPath(path, entry.path));
        const exported = JSON.stringify(definition.symbol);
        if (kind === "workflow")
          lines.push(`export { ${exported} as ${exported} } from ${module};`);
        else {
          lines.push(`import * as definition${index} from ${module};`);
          const value = definition.construction
            ? `definition${index}[${JSON.stringify(definition.construction.symbol)}][${JSON.stringify(definition.identity.name)}]`
            : `definition${index}[${exported}]`;
          values.push(
            kind === "activity" ? `[${JSON.stringify(definition.identity.name)}]: ${value}` : value,
          );
        }
      }
      if (kind === "activity") lines.push(`export const activities = { ${values.join(", ")} };`);
      if (kind === "nexus") lines.push(`export const nexusServices = [${values.join(", ")}];`);
      if (kind === "workflow" && !definitions.length) lines.push("export {};");
      artifacts.push({ path, content: `${lines.join("\n")}\n`, kind: "registration" });
    }
  }
  return { artifacts, diagnostics };
}

export const typescriptAdapter: NativeAdapter = { language: "typescript", analyze, emit };
